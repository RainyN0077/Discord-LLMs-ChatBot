/**
 * Theme data — migrated 1:1 from the legacy Svelte frontend
 * (frontend/src/lib/themes.js + frontend/src/lib/themeStore.js).
 *
 * Data model:
 * - BASE_COLORS: per-style base palette (20 keys per style)
 * - DEFAULTS: style-level fallback defaults (24 keys)
 * - 13 color schemes, each carrying a light and a dark variable set
 *   (34 keys each, except 'default' which only carries 4 sidebar keys)
 * - 9 styles referencing the shared scheme definitions; the scheme set
 *   applied at merge time is chosen by the style's `dark` classification
 *   (dark style → scheme.dark, light style → scheme.light), mirroring the
 *   legacy mkStyle(lightSchemes, darkSchemes) selection exactly.
 */

export type CssVarMap = Record<string, string>

export interface NamePair {
  zh: string
  en: string
}

export interface SchemeDef {
  id: string
  name: NamePair
  cssVars: {
    light: Partial<CssVarMap>
    dark: Partial<CssVarMap>
  }
}

export interface StyleDef {
  id: string
  name: NamePair
  cssVars: CssVarMap
  schemes: SchemeDef[]
  dark: boolean
}

