/**
 * Merge the four layers in the legacy order:
 * base colors → defaults → style vars → scheme vars.
 * The scheme layer picks light or dark depending on the style's
 * `dark` classification (dark style → scheme.dark, else scheme.light).
 */
export function mergeCssVars(styleId: string, schemeId: string): CssVarMap {
  const style = STYLES[styleId]
  if (!style) return { ...(BASE_COLORS.light ?? {}), ...DEFAULTS } as CssVarMap
  const base = BASE_COLORS[styleId] ?? BASE_COLORS.light
  const scheme = style.schemes.find((s) => s.id === schemeId) ?? style.schemes[0]
  const schemeVars = scheme ? (style.dark ? scheme.cssVars.dark : scheme.cssVars.light) : {}
  return { ...base, ...DEFAULTS, ...style.cssVars, ...schemeVars } as CssVarMap
}

/** Resolve a localized name: zh-prefixed locales → zh, everything else → en. */
export function localizedName(name: NamePair, locale: string): string {
  return locale.startsWith('zh') ? name.zh : name.en
}

export function isValidStyleId(id: string): boolean {
  return Object.prototype.hasOwnProperty.call(STYLES, id)
}

/** Return the vars in `{ '--bg-color': ... }` form for Vue `:style` binding. */
export function cssVarsToStyleObject(vars: CssVarMap): Record<string, string> {
  return Object.fromEntries(Object.entries(vars))
}

/**
 * DEV-only integrity check over the migrated theme data.
 * Throws on any violation (called from main.ts in dev builds).
 */
export function assertThemeDataIntegrity(): void {
  const errors: string[] = []
  const check = (ok: boolean, message: string): void => {
    if (!ok) errors.push(message)
  }

  // STYLE_ORDER ↔ STYLES keys correspond
  const styleKeys = Object.keys(STYLES)
  check(
    STYLE_ORDER.length === styleKeys.length &&
      STYLE_ORDER.every((id) => styleKeys.includes(id)) &&
      styleKeys.every((id) => (STYLE_ORDER as readonly string[]).includes(id)),
    'STYLE_ORDER does not match STYLES keys',
  )

  const cssVarKeySet = new Set<string>(CSS_VAR_KEYS)

  for (const styleId of STYLE_ORDER) {
    const style = STYLES[styleId]
    // every style has ≥ 1 scheme
    check(style && style.schemes.length >= 1, `style '${styleId}' has no schemes`)

    // style cssVars keys ⊆ 48 keys
    for (const key of Object.keys(style.cssVars)) {
      check(cssVarKeySet.has(key), `style '${styleId}' has unknown css var '${key}'`)
    }
  }

  // cyberpunk first scheme === 'samurai'
  check(STYLES.cyberpunk?.schemes[0]?.id === 'samurai', "cyberpunk first scheme is not 'samurai'")

  // per-scheme key-set checks
  const schemeById = new Map<string, SchemeDef>()
  for (const styleId of STYLE_ORDER) {
    for (const scheme of STYLES[styleId].schemes) {
      if (!schemeById.has(scheme.id)) schemeById.set(scheme.id, scheme)
    }
  }
  for (const schemeId of SCHEME_ORDER) {
    const scheme = schemeById.get(schemeId)
    check(!!scheme, `SCHEME_ORDER references missing scheme '${schemeId}'`)
    if (!scheme) continue
    const lightKeys = Object.keys(scheme.cssVars.light).sort()
    const darkKeys = Object.keys(scheme.cssVars.dark).sort()
    if (schemeId === 'default') {
      check(lightKeys.length === 4 && darkKeys.length === 4, `default scheme key count != 4`)
    } else {
      check(lightKeys.length === 34 && darkKeys.length === 34, `scheme '${schemeId}' key count != 34`)
    }
    check(
      JSON.stringify(lightKeys) === JSON.stringify(darkKeys),
      `scheme '${schemeId}' light/dark key sets differ`,
    )
  }

  // merged output covers all 48 keys with non-empty values for every style × scheme
  for (const styleId of STYLE_ORDER) {
    for (const scheme of STYLES[styleId].schemes) {
      const merged = mergeCssVars(styleId, scheme.id)
      for (const key of CSS_VAR_KEYS) {
        const value = merged[key]
        check(
          value !== undefined && value !== '',
          `mergeCssVars('${styleId}', '${scheme.id}') missing or empty '${key}'`,
        )
      }
    }
  }

  if (errors.length > 0) {
    console.error('Theme data integrity check failed:\n - ' + errors.join('\n - '))
    throw new Error(`Theme data integrity check failed (${errors.length} errors)`)
  }
}
